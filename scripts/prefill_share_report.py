"""J-2675 / F-3426: the READ job for the pe/pe_s/ec/ec_s fields core/model_client.call_node now writes onto
data/llm_latency.jsonl rows. Produces docs/lab/hot_lane_prefill_share_<date>.md: per caller, median prompt
tokens, median prefill seconds, median generation seconds, and prefill share of call time -- split into
human-turn windows vs everything else (idle thoughts and background).

READ-ONLY on live data (llm_latency.jsonl, optionally nascence.log); writes only the report file.

Human-turn windows are APPROXIMATE (inferred, not logged): with --from-log each `[CYCLE x] human:` line in
nascence.log opens a window of --window seconds (default 120; a human turn is ~11 sequential node calls /
~75 s wall per F-3425). Rows inside a window are labelled human, all others idle/background. A row-level
human-turn tag does not exist today; the report says so in its header.

    python scripts/prefill_share_report.py --since 2026-11-07 --from-log --node 11433
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

TREE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(TREE))

_DEFAULT_LAT = Path(r"C:\Nascence\data\llm_latency.jsonl")
_DEFAULT_LOG = Path(r"C:\Nascence\data\nascence.log")
_HUMAN = re.compile(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d),\d+ \[[^\]]*\] \[CYCLE [0-9a-f]+\] human:")


def human_windows_from_log(log_path: Path, window_s: float, since_ts: float = 0.0) -> list:
    wins = []
    try:
        with open(log_path, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = _HUMAN.match(line)
                if not m:
                    continue
                t = time.mktime(time.strptime(m.group(1), "%Y-%m-%d %H:%M:%S"))
                if t >= since_ts:
                    wins.append((t, t + window_s))
    except Exception:
        pass
    return wins


def _med(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2] if xs else None


def _fmt(v, nd=2):
    return "-" if v is None else (f"{v:.{nd}f}" if isinstance(v, float) else str(v))


def summarise(rows: list) -> dict:
    """{by: {...}} over ok rows. Rows lacking pe are counted in n but excluded from token stats."""
    from core import telemetry
    return telemetry.prefill_share_status(rows=rows)["by_caller"]


def aggregate(rows: list) -> dict:
    pe_s = sum(r["pe_s"] for r in rows if isinstance(r.get("pe_s"), (int, float)) and r.get("ok"))
    s = sum(r["s"] for r in rows if isinstance(r.get("pe_s"), (int, float)) and r.get("ok"))
    return {"n": len(rows), "n_pe_s": sum(1 for r in rows if isinstance(r.get("pe_s"), (int, float))),
            "share": round(pe_s / s, 3) if s > 0 else None}


def build(rows: list, windows: list, node: str | None, since: float, source: str) -> str:
    rows = [r for r in rows if isinstance(r, dict) and r.get("ts", 0) >= since
            and (node is None or r.get("node") == node)]
    with_pe = [r for r in rows if "pe" in r]

    def in_win(t):
        return any(a <= t <= b for a, b in windows)

    human = [r for r in with_pe if in_win(r["ts"])]
    idle = [r for r in with_pe if not in_win(r["ts"])]
    out = [f"# Hot lane prefill share ({time.strftime('%Y-%m-%d')})", "",
           f"Generated by scripts/prefill_share_report.py from {source}; node filter: {node or 'all'}; "
           f"{len(rows)} rows in range, {len(with_pe)} carry token counts (pe).", ""]
    if not windows:
        out += ["Human-turn windows: NONE supplied (no --from-log); every row is reported as one group.", ""]
    else:
        out += [f"Human-turn windows: {len(windows)}, derived from `[CYCLE x] human:` log lines. APPROXIMATE "
                f"(fixed-length window from the human line, inferred not logged): a background call that "
                f"overlaps a window is counted as human.", ""]
    for label, grp in (("human turn", human), ("idle / background", idle)) if windows else (("all", with_pe),):
        a = aggregate(grp)
        out += [f"## {label}: {a['n']} calls with counts, prefill share of call time "
                f"{_fmt(a['share'], 3)} (over {a['n_pe_s']} rows carrying prefill seconds)", ""]
        by = summarise(grp)
        out += ["| caller | node-calls | with pe | med prompt tok | med prefill s | med gen s | med call s | prefill share |",
                "|---|---|---|---|---|---|---|---|"]
        for k, v in sorted(by.items(), key=lambda kv: -kv[1]["n_total"]):
            out.append(f"| {k} | {v['n_total']} | {v['n_with_pe']} | {_fmt(v['med_prompt_tokens'], 0)} | "
                       f"{_fmt(v['med_prefill_s'])} | {_fmt(v['med_gen_s'])} | {_fmt(v['med_call_s'])} | "
                       f"{_fmt(v['prefill_share'], 3)} |")
        out.append("")
    out += ["Notes: llama.cpp project hubs report counts but no durations, so their prefill seconds/share are "
            "blank (unknown, not zero). `call s` includes lane-slot queueing, so share is prefill / "
            "(queue + request + parse)."]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lat", type=Path, default=_DEFAULT_LAT)
    ap.add_argument("--log", type=Path, default=_DEFAULT_LOG)
    ap.add_argument("--since", default="1970-01-01", help="YYYY-MM-DD local")
    ap.add_argument("--node", default=None, help="port suffix, e.g. 11433")
    ap.add_argument("--from-log", action="store_true")
    ap.add_argument("--window", type=float, default=120.0)
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    since = time.mktime(time.strptime(a.since, "%Y-%m-%d"))
    rows = []
    with open(a.lat, encoding="utf-8") as f:
        for line in f:
            try:
                rows.append(json.loads(line))
            except Exception:
                continue
    wins = human_windows_from_log(a.log, a.window, since) if a.from_log else []
    doc = build(rows, wins, a.node, since, str(a.lat))
    out = a.out or (TREE / "docs" / "lab" / f"hot_lane_prefill_share_{time.strftime('%Y-%m-%d')}.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
