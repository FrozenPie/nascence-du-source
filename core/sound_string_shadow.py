"""strings_and_sheets Phase 1 live wire, SHADOW ONLY (J-1963, D-0382; docs/staged/strings_and_sheets.md s3A/s5).

At each geometry-census moment, for every sound in `soundscape.active_sounds()`, compute that sound's CURRENT
point on its constructed onset/peak/tail string (data/sound_strings_constructed.json, a deterministic sidecar
regenerated by scripts/sound_strings_phase1_dryrun.py) and append one row per sound to
data/sound_strings_shadow.jsonl.

Hard guarantees (the plan's Phase 1 guards):
  * Writes ONLY data/sound_strings_shadow.jsonl. No prompt line, no fragment field, no store schema change,
    no read by any other loop (the founder's shadow read is the one reader -- the write-only-systems law).
  * Fail-open: record() never raises into geometry_census.snapshot() (except NonLiveWriteError is swallowed
    too -- an observe-only side effect, same as the census itself).
  * Kill-switch: SOUND_STRING_SHADOW = False -> record() is a no-op.
  * J-1979: EVENT keys take elapsed from the world's own firing stamp when one exists (row.clock == "fired";
    see _fired_ts), else presence age (clock == "presence"). row.past_end marks an event whose nominal
    onset+hold+tail is over -- a brief event sampled after it finished is honestly past its string, not "at the tail".
  * Honest limit (beds, and events with no stamp): `active_sounds()` is a stateless "what is gated-on now" list, not an acoustic event clock.
    `elapsed_s` is therefore PRESENCE age: seconds since the key was first seen in an active set at a census
    moment (an upper bound on true sound age, and 0.0 on first sight). Events (call/thump/wingbeat) walk
    onset -> peak -> tail on the nominal timescales below; beds (bed/bed_like) ramp onset -> peak and then
    HOLD the peak (their tail is the moment they leave the active set, which this log cannot see). The
    timescales are nominal pre-registered constants, not measurements.
"""
from __future__ import annotations

import json
import logging
import threading
import time
from pathlib import Path

from core import profile

logger = logging.getLogger(__name__)

SOUND_STRING_SHADOW = True            # kill-switch: False -> record() does nothing

_DATA = Path(__file__).parent.parent / "data"
_SIDECAR = _DATA / "sound_strings_constructed.json"
_LOG = _DATA / "sound_strings_shadow.jsonl"      # tests must temp-path this, never truncate the live file
_MAX_LOG_BYTES = 200 * 1024 * 1024               # runaway guard: stop appending past 200 MB

_AXES = ("brightness", "energy", "onset", "periodicity", "roughness", "continuity")
_RESET_GAP_S = 600.0                              # absent from census this long -> a new presence starts

# (onset-ramp s, peak-hold s, tail-decay s); None hold/tail = a bed: ramp then hold the peak.
_TIMESCALES = {
    "call":     (0.8, 2.0, 3.0),
    "thump":    (0.1, 0.2, 1.0),
    "wingbeat": (0.5, 3.0, 1.5),
    "bed":      (6.0, None, None),
    "bed_like": (6.0, None, None),
}
_DEFAULT_SCALE = _TIMESCALES["bed"]

_lock = threading.Lock()
_first_seen: dict[str, float] = {}               # key -> ts first seen in the current presence
_last_seen: dict[str, float] = {}                # key -> ts last seen
_sidecar_cache: dict = {"mtime": None, "data": None}


# ---- J-1979: a real onset clock for EVENT keys ------------------------------------------------------------
# active_sounds() is a stateless gate; presence age (first seen at a census moment) is only an upper bound on
# a brief event's age, so events sat at the tail vertex ~73% of rows (F-2580). Where the world records WHEN the
# act/event actually fired, we read that timestamp (read-only; no state module is edited) and use
# now - fired_ts as elapsed. Sources, all existing timestamps the soundscape's own act-recency gates read:
#   reading.py last_read_ts (page_turn) | letters.last_write_ts (pen_scratch) | locomotion desk_ts / gate_ts |
#   room_state stoke_ts / study.door_ts / wood_snap_ts / wood_haul_ts | garden last_water/harvest/sow_ts |
#   cat_sounds._mem["last_fired"] (the cat's per-key emission stamp, in-process).
# Anything with no stamp (and every bed) keeps the presence clock; the row says which via `clock`.
_MAX_FIRED_AGE_S = 3600.0    # a stamp older than this is not "the event that is sounding now": use presence


def _safe(fn):
    try:
        v = fn()
        return float(v) if v else None
    except Exception:
        return None


def _room() -> dict:
    try:
        return json.loads((_DATA / "room_state.json").read_text(encoding="utf-8"))
    except Exception:
        return {}


def _fired_ts(key: str) -> float | None:
    """Read-only: the timestamp the world last recorded this event key firing, or None if it keeps none."""
    try:
        if key == "page_turn":
            from core import reading as _rd
            st = _rd._load_state()
            return _safe(lambda: st.get(st.get("_current_book"), {}).get("last_read_ts"))
        if key == "pen_scratch":
            from core import letters as _lt
            return _safe(_lt.last_write_ts)
        if key == "chair_desk_scrape":
            from core import locomotion as _lc
            return _safe(lambda: _lc._load().get("desk_ts"))
        if key == "gate_latch":
            from core import locomotion as _lc
            return _safe(lambda: _lc._load().get("gate_ts"))
        room_keys = {"log_on_fire": ("stoke_ts",), "door_sound": ("study", "door_ts"),
                     "wood_snap": ("wood_snap_ts",), "wood_haul_clatter": ("wood_haul_ts",)}
        if key in room_keys:
            d = _room()
            for part in room_keys[key]:
                d = d.get(part) if isinstance(d, dict) else None
            return _safe(lambda: d)
        garden_keys = {"bed_watering": "last_water_ts", "herb_cut": "last_harvest_ts", "sow_dig": "last_sow_ts"}
        if key in garden_keys:
            from core import garden as _g
            return _safe(lambda: _g._load().get(garden_keys[key]))
        from core import cat_sounds as _cs
        return _safe(lambda: _cs._mem.get("last_fired", {}).get(key))
    except Exception:
        return None


def _event_elapsed(key: str, ts: float) -> float | None:
    """Seconds since this event key really fired, or None (no stamp / stale / in the future by > 5 s)."""
    try:
        f = _fired_ts(key)
    except Exception:
        return None
    if f is None:
        return None
    age = ts - f
    if age < -5.0 or age > _MAX_FIRED_AGE_S:
        return None
    return max(0.0, age)


def _past_end(entry: dict, elapsed_s: float) -> bool:
    """True when an event's nominal onset+hold+tail is over (it has finished sounding); beds never end here."""
    t_on, t_hold, t_tail = _TIMESCALES.get(entry.get("archetype"), _DEFAULT_SCALE)
    return t_hold is not None and elapsed_s > t_on + t_hold + t_tail


def _load_sidecar() -> dict | None:
    try:
        mt = _SIDECAR.stat().st_mtime
    except OSError:
        return None
    if _sidecar_cache["mtime"] != mt:
        try:
            _sidecar_cache["data"] = json.loads(_SIDECAR.read_text(encoding="utf-8"))
            _sidecar_cache["mtime"] = mt
        except Exception as exc:
            logger.debug("[sound-string-shadow] sidecar unreadable (non-fatal): %s", exc)
            return None
    return _sidecar_cache["data"]


def _lerp(a: dict, b: dict, t: float) -> dict:
    t = max(0.0, min(1.0, t))
    return {x: round(float(a[x]) + (float(b[x]) - float(a[x])) * t, 4) for x in _AXES}


def _dist(a: dict, b: dict) -> float:
    return round(sum((float(a[x]) - float(b[x])) ** 2 for x in _AXES) ** 0.5, 4)


def point_on_string(entry: dict, elapsed_s: float) -> tuple[dict, str, tuple[str, str]]:
    """Pure: (point, phase, bracket) for `entry` (one sidecar record) at presence age `elapsed_s`.
    phase in {onset, peak, tail, body}; bracket = the two string vertices the point lies between
    (equal when the point sits on a vertex)."""
    s = entry["string"]
    on, pk, tl = s["onset"], s["peak"], s["tail"]
    t_on, t_hold, t_tail = _TIMESCALES.get(entry.get("archetype"), _DEFAULT_SCALE)
    if elapsed_s < t_on:
        return _lerp(on, pk, elapsed_s / t_on if t_on > 0 else 1.0), "onset", ("onset", "peak")
    if t_hold is None:                               # a bed: hold the long flat body at the peak
        return dict(pk), "body", ("peak", "peak")
    e = elapsed_s - t_on
    if e < t_hold:
        return dict(pk), "peak", ("peak", "peak")
    e -= t_hold
    if e < t_tail:
        return _lerp(pk, tl, e / t_tail), "tail", ("peak", "tail")
    return dict(tl), "tail", ("tail", "tail")


def _nearest_vertex(entry: dict, point: dict, bracket: tuple | None = None) -> tuple[str, bool]:
    """(vertex, tie). J-2067: deterministic on ties -- among equidistant vertices prefer one the phase clock
    names (the bracket), then fixed onset<peak<tail order; the caller logs tie=true."""
    s = entry["string"]
    ds = {v: _dist(s[v], point) for v in ("onset", "peak", "tail")}
    best = min(ds.values())
    tied = [v for v in ("onset", "peak", "tail") if ds[v] == best]
    if len(tied) == 1:
        return tied[0], False
    for v in (bracket or ()):
        if v in tied:
            return v, True
    return tied[0], True


def record(active: list | None, source: str = "?", now: float | None = None, n_active: int | None = None) -> int:
    """Append one shadow row per active sound. Returns rows written (0 on any no-op/failure). Never raises."""
    if not SOUND_STRING_SHADOW or not active:
        return 0
    try:
        _log = profile.guard_path(_LOG)             # resolve BEFORE any I/O; refusal swallowed below
    except Exception as exc:                        # NonLiveWriteError or anything else: observe-only, no row
        logger.debug("[sound-string-shadow] refused by the fence (non-live): %s", exc)
        return 0
    try:
        sidecar = _load_sidecar()
        if not sidecar:
            return 0
        ts = time.time() if now is None else float(now)
        keys = [k for k in active if isinstance(k, str)]
        rows = []
        with _lock:
            for k in list(_last_seen):               # presences that lapsed past the reset gap restart
                if k not in keys and ts - _last_seen[k] > _RESET_GAP_S:
                    _first_seen.pop(k, None)
                    _last_seen.pop(k, None)
            for k in keys:
                entry = sidecar.get(k)
                if not entry:
                    continue
                first = k not in _first_seen or ts - _last_seen.get(k, ts) > _RESET_GAP_S
                if first:
                    _first_seen[k] = ts
                _last_seen[k] = ts
                elapsed = max(0.0, ts - _first_seen[k])
                clock = "presence"
                if entry.get("archetype") not in ("bed", "bed_like", None):
                    ev = _event_elapsed(k, ts)
                    if ev is not None:
                        elapsed, clock = ev, "fired"
                pt, phase, bracket = point_on_string(entry, elapsed)
                nearest, tie = _nearest_vertex(entry, pt, bracket)
                rows.append({
                    "ts": round(ts, 1), "source": source, "key": k, "archetype": entry.get("archetype"),
                    "n_active": n_active if n_active is not None else len(keys),
                    "first_sight": bool(first), "elapsed_s": round(elapsed, 1), "clock": clock,
                    "past_end": _past_end(entry, elapsed), "phase": phase,
                    "point": pt, "d_peak": _dist(pt, entry["string"]["peak"]),
                    "d_fixed": _dist(pt, entry["fixed_point"]),
                    "nearest_vertex": nearest, "agree": nearest in bracket, "tie": tie,
                })
        if not rows:
            return 0
        try:
            if _log.exists() and _log.stat().st_size > _MAX_LOG_BYTES:
                return 0
        except OSError:
            pass
        _log.parent.mkdir(parents=True, exist_ok=True)
        with open(_log, "a", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        return len(rows)
    except Exception as exc:
        logger.debug("[sound-string-shadow] record failed (non-fatal): %s", exc)
        return 0
